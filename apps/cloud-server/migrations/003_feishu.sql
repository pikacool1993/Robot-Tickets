CREATE TABLE IF NOT EXISTS agent_feishu_configs (
 agent_id CHAR(36) PRIMARY KEY,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 order_created BOOLEAN NOT NULL DEFAULT TRUE,
 auth_expired BOOLEAN NOT NULL DEFAULT TRUE,
 order_blocked BOOLEAN NOT NULL DEFAULT TRUE,
 webhook_ciphertext VARBINARY(1024) NOT NULL,
 webhook_nonce BINARY(12) NOT NULL,
 webhook_key_version VARCHAR(32) NOT NULL,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_feishu_agent FOREIGN KEY (agent_id) REFERENCES agents(id) ON DELETE CASCADE
) ENGINE=InnoDB;
